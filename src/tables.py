"""Markdown results tables, made only from CSV files in results/.

Writes results/summary_tables.md. Values are rounded to the shown number of
decimals (nearest), nothing else is changed. The README copies these tables.
"""
import pandas as pd

from common import RESULTS_DIR

RES = RESULTS_DIR / "resolution"
ATT = RESULTS_DIR / "attention"


def md(df: pd.DataFrame) -> str:
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "|".join("---" for _ in cols) + "|"]
    for _, r in df.iterrows():
        lines.append("| " + " | ".join("" if pd.isna(v) else str(v) for v in r) + " |")
    return "\n".join(lines)


def f(v, nd=2):
    return None if pd.isna(v) else f"{v:.{nd}f}"


def imagenette() -> str:
    acc = pd.read_csv(RESULTS_DIR / "accuracy.csv")
    lat = pd.read_csv(RESULTS_DIR / "latency.csv")
    mem = pd.read_csv(RESULTS_DIR / "memory.csv")
    d = acc.merge(lat, on="method", suffixes=("", "_l")).merge(mem, on="method", suffixes=("", "_m"))
    keep = ["fp32", "int8", "tome_r0", "tome_r8", "tome_r12", "tome_r16", "tome_r24",
            "tome_r8_int8", "tome_r16_int8", "tome_r24_int8"]
    d = d.set_index("method").loc[keep].reset_index()
    out = pd.DataFrame({
        "method": d.method,
        "top-1 10-class (%)": (d.top1_restricted * 100).map(f),
        "top-1 1000-class (%)": (d.top1_unrestricted * 100).map(f),
        "latency median (ms)": d.latency_median_ms.map(f),
        "latency p95 (ms)": d.latency_p95_ms.map(f),
        "throughput (img/s)": d.throughput_img_per_s.map(f),
        "peak memory (MB)": d.peak_total_mb.map(f),
        "size on disk (MB)": d.size_on_disk_mb.map(f),
        "tokens after last block": d.tokens_out.astype(int),
    })
    return md(out)


def resolution() -> str:
    lat = pd.read_csv(RES / "latency.csv")
    mem = pd.read_csv(RES / "memory.csv")
    agr = pd.read_csv(RES / "agreement.csv")
    d = lat.merge(mem[["method", "input_size", "peak_total_mb", "inference_increment_mb"]],
                  on=["method", "input_size"], how="left") \
           .merge(agr[["method", "input_size", "n_agree_with_fp32", "n_frames", "status"]],
                  on=["method", "input_size"], how="left", suffixes=("", "_agr"))
    rows = []
    for _, r in d.iterrows():
        ok = r.status == "ok"
        agree = (f"{int(r.n_agree_with_fp32)}/{int(r.n_frames)}" if r.status_agr == "ok"
                 else "not run")
        rows.append({
            "input (HxW)": r.input_size,
            "tokens in": int(r.n_patches + 1),
            "method": r.method,
            "r per block": "" if pd.isna(r.tome_r_per_block) else int(r.tome_r_per_block),
            "tokens after last block": int(r.tokens_out) if ok else "",
            "latency median (ms)": f(r.latency_median_ms) if ok else "skipped",
            "run 1 / run 2 (ms)": (f"{f(r.run1_latency_median_ms)} / "
                                   f"{f(r.run2_latency_median_ms) or 'skipped'}") if ok else "",
            "throughput (img/s)": f(r.throughput_img_per_s, 3) if ok else "",
            "peak memory (MB)": f(r.peak_total_mb) if ok else "",
            "top-1 same as FP32": "-" if r.method == "fp32" and r.status_agr == "ok" else agree,
        })
    return md(pd.DataFrame(rows))


def attention() -> str:
    t, m = pd.read_csv(ATT / "timing.csv"), pd.read_csv(ATT / "memory.csv")
    rows = []
    for n in sorted(t.seq_len.unique()):
        row = {"N": n}
        for meth in ["naive", "sdpa"]:
            tt = t[(t.method == meth) & (t.seq_len == n)].iloc[0]
            mm = m[(m.method == meth) & (m.seq_len == n)].iloc[0]
            row[f"{meth} time median (ms)"] = f(tt.latency_median_ms, 3) if tt.status == "ok" else "skipped"
            row[f"{meth} memory added (MB)"] = f(mm.call_increment_mb) if mm.status == "ok" else "skipped"
        rows.append(row)
    return md(pd.DataFrame(rows))


def main() -> None:
    text = "\n\n".join([
        "# Results tables (generated by src/tables.py from results/*.csv)",
        "## Imagenette (DeiT-Tiny, 224 px, batch 1)\n\n" + imagenette(),
        "## Resolution scaling on KITTI (DeiT-Tiny, batch 1)\n\n" + resolution(),
        "## Attention scaling (synthetic, batch 1, 3 heads, head dim 64)\n\n" + attention(),
    ]) + "\n"
    (RESULTS_DIR / "summary_tables.md").write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
